/*
 * DFO Online mods - which mods there are, and running their patches on a view.
 *
 * A mod is a folder beside modloader/ (`../<name>-mod/`) with a patches.mjs that
 * exports ID, NAME, SPEC and patch(store, log). Discovery is by that file, so a
 * new mod needs no registration anywhere else.
 */
'use strict';

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { MODLOADER_ROOT } from './view.mjs';

/** Every mod in the workspace, in id order. Throws on a malformed patches.mjs. */
export async function discoverMods() {
  const root = path.dirname(MODLOADER_ROOT);
  let names = [];
  try { names = fs.readdirSync(root).sort(); } catch { return []; }
  const mods = [];
  for (const name of names) {
    const file = path.join(root, name, 'patches.mjs');
    if (!fs.existsSync(file)) continue;
    const m = await import(pathToFileURL(file).href);
    if (typeof m.ID !== 'string' || typeof m.NAME !== 'string' || typeof m.SPEC !== 'string' || typeof m.patch !== 'function') {
      throw new Error(`${name}/patches.mjs must export ID, NAME, SPEC and patch()`);
    }
    mods.push({ id: m.ID, name: m.NAME, spec: m.SPEC, dir: name, patch: m.patch });
  }
  return mods.sort((a, b) => a.id.localeCompare(b.id));
}

/**
 * Run every mod's patch on `view`, one after another. A mod whose patch throws
 * (an anchor is missing, the chunk is gone) is rolled back out of the view and
 * left out of the registry; the others still apply.
 */
export function runPatches(view, mods, log = () => {}) {
  const registry = [];
  const failed = [];
  for (const mod of mods) {
    const snap = view.snapshot();
    try {
      mod.patch(view, (msg) => log(`[${mod.id}] ${msg}`));
      registry.push({ id: mod.id, name: mod.name, spec: mod.spec });
    } catch (e) {
      view.restore(snap);
      failed.push({ id: mod.id, why: e?.message || String(e) });
      log(`[${mod.id}] not applied: ${e?.message || e}`);
    }
  }
  return { registry, failed };
}

/** The served registry module: one entry per mod that applied. */
export function renderRegistry(registry) {
  const list = registry.map((m) => ({ id: m.id, name: m.name, spec: m.spec }));
  return `// generated by the DFO mods launcher - one entry per mod that applied to this build\n`
    + `export const MODS = ${JSON.stringify(list)};\n`;
}
